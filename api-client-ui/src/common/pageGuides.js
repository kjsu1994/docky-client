export const getPageGuide = (pathname, context = {}) => {
    const path = pathname || "/";
    const boardGame = boardGameGuideRoutes[path];
    if (boardGame) {
        return getBoardGameRuleGuide({
            ...context,
            game: boardGame,
        });
    }
    return guides.find((guide) => guide.test(path)) || fallbackGuide;
};
