const objectParticle = (word) => {
    const lastChar = String(word || "").trim().slice(-1);
    const code = lastChar.charCodeAt(0);
    if (code < 0xac00 || code > 0xd7a3) return "을";
    return (code - 0xac00) % 28 === 0 ? "를" : "을";
};

